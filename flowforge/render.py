"""Deterministic export for the supported workflow subset.

This renderer produces a useful UiPath-shaped XAML draft. Exact activity
serialization is package/version-specific, so the renderer preserves all
properties and makes that boundary explicit rather than silently claiming to
support every UiPath package.
"""

from __future__ import annotations

import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any

from .model import ActivityNode, WorkflowProject


ACTIVITIES_NS = "http://schemas.microsoft.com/netfx/2009/xaml/activities"
UI_NS = "http://schemas.uipath.com/workflow/activities"
X_NS = "http://schemas.microsoft.com/winfx/2006/xaml"
FLOWFORGE_NS = "https://flowforge.dev/schema/2026"

ET.register_namespace("", ACTIVITIES_NS)
ET.register_namespace("ui", UI_NS)
ET.register_namespace("x", X_NS)
ET.register_namespace("flowforge", FLOWFORGE_NS)


def _safe_class_name(name: str) -> str:
    value = re.sub(r"[^A-Za-z0-9_]", "_", name).strip("_") or "FlowForgeProject"
    if value[0].isdigit():
        value = f"Project_{value}"
    return value


def _display_value(value: Any) -> str:
    if isinstance(value, (dict, list)):
        if isinstance(value, dict) and set(value) == {"selector"}:
            return str(value["selector"])
        return json.dumps(value, sort_keys=True, separators=(",", ":"))
    if isinstance(value, bool):
        return str(value).lower()
    return str(value)


def _tag_for(node_type: str) -> str:
    if node_type == "Sequence" or node_type == "If" or node_type in {"ForEach", "While"}:
        return f"{{{ACTIVITIES_NS}}}{node_type}"
    return f"{{{UI_NS}}}{node_type}"


def _property_name(name: str) -> str:
    return name[:1].upper() + name[1:]


def _append_properties(element: ET.Element, node: ActivityNode) -> None:
    for name in sorted(node.properties):
        element.set(_property_name(name), _display_value(node.properties[name]))


def _append_node(parent: ET.Element, node: ActivityNode) -> None:
    element = ET.SubElement(
        parent,
        _tag_for(node.type),
        {
            f"{{{X_NS}}}Name": node.id,
            "DisplayName": str(node.properties.get("display_name", node.type)),
        },
    )
    _append_properties(element, node)
    if node.type == "If":
        for branch_name, label in (("then", "Then"), ("else", "Else")):
            if branch_name in node.branches:
                branch = ET.SubElement(element, f"{{{ACTIVITIES_NS}}}If.{label}")
                sequence = ET.SubElement(branch, f"{{{ACTIVITIES_NS}}}Sequence", {"DisplayName": label})
                for child in node.branches[branch_name]:
                    _append_node(sequence, child)
    else:
        for child in node.children:
            _append_node(element, child)
        for branch_name, children in node.branches.items():
            branch = ET.SubElement(element, f"{{{FLOWFORGE_NS}}}Branch", {"Name": branch_name})
            for child in children:
                _append_node(branch, child)


def render_xaml(project: WorkflowProject) -> str:
    """Render a stable XAML draft from a project."""

    root = ET.Element(
        f"{{{ACTIVITIES_NS}}}Activity",
        {
            f"{{{X_NS}}}Class": f"{_safe_class_name(project.name)}.Main",
            "DisplayName": project.name,
        },
    )
    sequence = ET.SubElement(
        root,
        f"{{{ACTIVITIES_NS}}}Sequence",
        {
            f"{{{X_NS}}}Name": project.root.id,
            "DisplayName": "Main",
        },
    )
    for child in project.root.children:
        _append_node(sequence, child)
    xml = ET.tostring(root, encoding="unicode", short_empty_elements=True)
    return f"<?xml version=\"1.0\" encoding=\"utf-8\"?>\n{xml}\n"


def render_project(project: WorkflowProject, output_dir: str | Path) -> list[Path]:
    """Write the XAML draft and metadata files, returning created paths."""

    directory = Path(output_dir)
    directory.mkdir(parents=True, exist_ok=True)
    xaml_path = directory / "Main.xaml"
    project_path = directory / "project.json"
    model_path = directory / "flowforge.json"
    xaml_path.write_text(render_xaml(project), encoding="utf-8")
    project_path.write_text(
        json.dumps(
            {
                "name": project.name,
                "description": "Generated by FlowForge",
                "main": "Main.xaml",
                "dependencies": project.dependencies,
                "runtimeOptions": {"autoDispose": True},
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    model_path.write_text(json.dumps(project.to_dict(), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return [xaml_path, project_path, model_path]
